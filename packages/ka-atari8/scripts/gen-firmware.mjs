// Regenerates src/firmware.ts from vendor/altirraos-xl-xe.rom (see vendor/VENDORED.md).
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const rom = readFileSync(new URL('../vendor/altirraos-xl-xe.rom', import.meta.url))
const sha256 = createHash('sha256').update(rom).digest('hex')
const base64 = rom.toString('base64').replace(/(.{100})/g, '$1\n  ')

writeFileSync(
  new URL('../src/firmware.ts', import.meta.url),
  `// Generated by scripts/gen-firmware.mjs from vendor/altirraos-xl-xe.rom. Do not edit.
// AltirraOS (c) Avery Lee, FSF all-permissive licence; see vendor/VENDORED.md.
export const ALTIRRA_OS_XL_XE_SHA256 = '${sha256}'

const BASE64 =
  '${base64.split('\n  ').join("' +\n  '")}'

/** The AltirraOS XL/XE ROM image (16 KB): a clean-room replacement for the Atari XL/XE operating system. */
export function altirraOsXlXe(): Uint8Array {
  const binary = atob(BASE64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return bytes
}
`,
)
console.log('wrote src/firmware.ts', rom.length, 'bytes', sha256)
